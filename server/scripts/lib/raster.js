export function canvas(width, height, bg = [240, 240, 236]) {
  const png = new PNG({ width, height });
  const c = {
    png,
    width,
    height,
    set(x, y, [r, g, b], a = 1) {
      x = Math.round(x); y = Math.round(y);
      if (x < 0 || y < 0 || x >= width || y >= height) return;
      const i = (y * width + x) * 4;
      const d = png.data;
      d[i] = d[i] * (1 - a) + r * a;
      d[i + 1] = d[i + 1] * (1 - a) + g * a;
      d[i + 2] = d[i + 2] * (1 - a) + b * a;
      d[i + 3] = 255;
    },
    rect(x, y, w, h, color, a = 1) {
      for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) c.set(xx, yy, color, a);
    },
    stroke(x, y, w, h, color, t = 2) {
      c.rect(x, y, w, t, color); c.rect(x, y + h - t, w, t, color);
      c.rect(x, y, t, h, color); c.rect(x + w - t, y, t, h, color);
    },
    line(x0, y0, x1, y1, color, t = 2) {
      const steps = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0)) || 1;
      for (let s = 0; s <= steps; s++) {
        const x = x0 + ((x1 - x0) * s) / steps;
        const y = y0 + ((y1 - y0) * s) / steps;
        c.rect(Math.round(x - t / 2), Math.round(y - t / 2), t, t, color);
      }
    },
    circle(cx, cy, r, color, a = 1) {
      for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) if (x * x + y * y <= r * r) c.set(cx + x, cy + y, color, a);
    },
    text(str, x, y, scale = 3, color = [30, 30, 30]) {
      let cx = x;
      for (const ch of String(str).toUpperCase()) {
        const glyph = FONT[ch] ?? FONT[' '];
        glyph.forEach((row, gy) => {
          [...row].forEach((bit, gx) => { if (bit === '1') c.rect(cx + gx * scale, y + gy * scale, scale, scale, color); });
        });
        cx += 6 * scale;
      }
      return cx;
    },
    textWidth: (str, scale = 3) => String(str).length * 6 * scale,
    noise(amount, seed = 1) {
      let s = seed;
      const rand = () => ((s = (s * 16807) % 2147483647) / 2147483647);
      for (let i = 0; i < png.data.length; i += 4) {
        const n = (rand() - 0.5) * amount;
        png.data[i] = Math.max(0, Math.min(255, png.data[i] + n));
        png.data[i + 1] = Math.max(0, Math.min(255, png.data[i + 1] + n));
        png.data[i + 2] = Math.max(0, Math.min(255, png.data[i + 2] + n));
      }
    },
    toBuffer: () => PNG.sync.write(png),
  };
  c.rect(0, 0, width, height, bg);
  return c;
}

/** Exhibit sticker in the bottom-right corner, like a court evidence tag. */
export function exhibitTag(c, label) {
  const w = c.textWidth(label, 3) + 28;
  const x = c.width - w - 18;
  const y = c.height - 52;
  c.rect(x, y, w, 36, [250, 246, 214]);
  c.stroke(x, y, w, 36, [120, 110, 70], 2);
  c.text(label, x + 14, y + 8, 3, [70, 60, 30]);
}
